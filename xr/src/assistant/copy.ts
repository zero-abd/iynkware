export type Vars = Readonly<Record<string, string | number>>;

/** The string for `key` in `lang`, else English's, with `{name}` placeholders filled. A missing var stays as written. */
export function say(lang: Lang, key: CopyKey, vars?: Vars): string {
  const text = COPY[lang]?.[key] || COPY.en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole)) : text;
}

/** One key in all six languages, for contract fields that carry `LocalizedText` (a co-builder's name). */
export function localized(key: CopyKey): LocalizedText {
  return Object.fromEntries(Object.entries(COPY).map(([lang, table]) => [lang, table[key]])) as LocalizedText;
}

export const COPY_KEYS: readonly CopyKey[] = KEYS;
